#!/usr/bin/env python3
"""Build the offline manual library from checked-in sources; no downloads or installs.
Requires Python 3, groff and col. Output: ../manuals-data.js.
"""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import hashlib,json,re,subprocess
ROOT=Path(__file__).resolve().parent
manifest=json.loads((ROOT/'manifest.json').read_text())
def build(entry):
    source=(ROOT/'sources'/entry['file']).read_text()
    assert hashlib.sha256(source.encode()).hexdigest()==entry['sha256'],entry['id']
    if entry['format']=='roff':
        rendered=subprocess.run(['groff','-S','-Tutf8','-mandoc','-rLL=100n','-rLT=100n'],input=source,text=True,capture_output=True,check=True)
        if 'cannot open' in rendered.stderr: raise ValueError(entry['id']+': '+rendered.stderr)
        text=subprocess.run(['col','-bx'],input=rendered.stdout,text=True,capture_output=True,check=True).stdout
    else:
        text=source
    text=re.sub(r'\n{4,}','\n\n\n',text).strip()
    assert len(text)>80,entry['id']
    result={k:v for k,v in entry.items() if k not in ['file','format']}
    result.update(title=f"{entry['name']}({entry['section']})",text=text,originalSource=source)
    return result
with ThreadPoolExecutor(max_workers=6) as workers:
    manuals=list(workers.map(build,manifest['entries']))
manuals.sort(key=lambda x:(x['name'],x['section']))
bundle=dict(captured=manifest['captured'],manuals=manuals,coverageNotes=manifest['coverageNotes'],notices={key:(ROOT/'notices'/file).read_text() for key,file in manifest['notices'].items()})
# Escape HTML delimiters so the same JS can be embedded safely in a script element.
payload=json.dumps(bundle,ensure_ascii=False,separators=(',',':')).replace('<','\\u003c').replace('>','\\u003e').replace('&','\\u0026')
output=ROOT.parent/'manuals-data.js'
output.write_text('// Generated by manuals/build-manuals.py from bundled manual sources.\nwindow.OFFLINE_MANUALS = '+payload+';\n')
print(f'Built {len(manuals)} full manual entries: {output.stat().st_size/1024/1024:.1f} MiB')
