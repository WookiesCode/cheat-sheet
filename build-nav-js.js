// build-nav-js.js
// The full top nav (~140 KB of menus and logos) used to be copied into every page. It now
// lives once, in nav/nav-source.html (the generators and build-nav-groups.js edit it), and
// this step:
//   1. writes it into nav.js, and
//   2. gives every page a small fallback nav (the same top row of links, without the
//      drop-down menus), followed directly by <script src="nav.js">.
// The script runs synchronously right after </nav>, so the full menus are in place before
// the rest of the page is parsed or painted, and before common.js reads them (suite rail,
// pager, Practice). Without JavaScript the fallback still links every tab's hub page.
// Re-runnable: pages that already have the fallback and the script are left alone.
const fs = require('fs');
const path = require('path');
const { NAV_SOURCE } = require('./nav/targets');

const NAV = /(<nav class="sheet-switcher" aria-label="Switch cheat sheet">)([\s\S]*?)(\n(\s*)<\/nav>)/;
// The portable copy builds its own nav; omarchy.html has a nav of its own.
const SKIP = new Set(['datacenter-cheatsheet-portable.html', 'omarchy.html']);

const source = fs.readFileSync(path.join(__dirname, NAV_SOURCE), 'utf8').match(NAV);
if (!source) throw new Error(`No <nav class="sheet-switcher"> in ${NAV_SOURCE}`);
const full = source[2];

// Drop every drop-down menu (its end is found by counting <div> depth; menus nest divs).
function withoutMenus(html) {
  const open = '<div class="nav-dropdown-menu';
  let out = '', i = 0;
  for (;;) {
    const start = html.indexOf(open, i);
    if (start < 0) return out + html.slice(i);
    const rx = /<div\b|<\/div>/g;
    rx.lastIndex = start;
    let depth = 0, m, end = -1;
    while ((m = rx.exec(html))) {
      depth += m[0] === '</div>' ? -1 : 1;
      if (depth === 0) { end = m.index + 6; break; }
    }
    if (end < 0) throw new Error('Unbalanced <div> in a nav menu');
    out += html.slice(i, start).replace(/\s+$/, '');
    i = end;
  }
}
const fallback = withoutMenus(full);

const js = `// nav.js: generated by build-nav-js.js from ${NAV_SOURCE}. Edit the source, not this file.
// Each page loads this right after its small fallback <nav> and swaps in the full menus.
(function () {
  var script = document.currentScript, nav = script && script.previousElementSibling;
  if (!nav || !nav.matches('nav.sheet-switcher')) return;
  nav.innerHTML = ${JSON.stringify(full)};
})();
`;
const jsPath = path.join(__dirname, 'nav.js');
if (!fs.existsSync(jsPath) || fs.readFileSync(jsPath, 'utf8') !== js) fs.writeFileSync(jsPath, js, 'utf8');

let changed = 0;
const SCRIPT_AFTER = /^\s*<script src="nav\.js(\?v=[0-9a-f]*)?"><\/script>/;
for (const file of fs.readdirSync(__dirname).filter(f => f.endsWith('.html') && !SKIP.has(f))) {
  const p = path.join(__dirname, file);
  const before = fs.readFileSync(p, 'utf8');
  const m = before.match(NAV);
  if (!m) continue;
  const end = m.index + m[0].length;
  const hasScript = SCRIPT_AFTER.test(before.slice(end));
  const after = before.slice(0, m.index) + m[1] + fallback + m[3]
    + (hasScript ? '' : `\n${m[4]}<script src="nav.js"></script>`) + before.slice(end);
  if (after !== before) { fs.writeFileSync(p, after, 'utf8'); changed++; }
}
console.log(`nav.js: ${(Buffer.byteLength(js) / 1024).toFixed(0)} KB; fallback nav ${(Buffer.byteLength(fallback) / 1024).toFixed(1)} KB; ${changed} page(s) updated`);
