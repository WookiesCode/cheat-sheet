// build-index.js
// Generates global-search-index.js across every interactive cheat sheet JS data file.
const fs = require('fs');
const path = require('path');
const { isReference } = require('./build-reference-rules.js');

// Tooling never holds sheet data. app.js does: it backs linux.html (index.html is the home page).
const isTooling = f => /^(build-|generate-|create-)/.test(f) || f === 'common.js' || f === 'global-search-index.js' || f === 'man-pages-data.js' || f === 'flag-index.js';
const htmlFor = f => (f === 'app.js' ? 'linux.html' : f.replace(/\.js$/, '.html'));

const jsFiles = fs.readdirSync(__dirname).filter(f => f.endsWith('.js') && !isTooling(f));

const index = [];

// Flag index for "Explain a command": tool → flag or subcommand → [explanation, sheet].
// Harvested from every card's flag notes, so pasted commands are explained in the
// site's own words before falling back to the man pages.
const flagIndex = {};
const WRAPPERS = /^(sudo|doas|env|time|nohup|nice|ionice|stdbuf|timeout|watch|exec|command|builtin|xargs)$/;
function toolOf(cmd) {
  const words = String(cmd || '').trim().split(/\s+/);
  for (let i = 0; i < words.length; i++) {
    const w = words[i].replace(/^\$\s*/, '');
    if (!w || /^[A-Z_][A-Z0-9_]*=/.test(w) || WRAPPERS.test(w) || /^-/.test(w) || /^\d+$/.test(w)) continue;
    const base = w.replace(/^.*\//, '');
    return /^[A-Za-z][\w.+-]*$/.test(base) ? base : '';
  }
  return '';
}
function flagKeys(token) {
  const t = String(token || '').trim();
  if (/^-/.test(t)) {
    // "-r -u -p", "-d / -c / -4", "--sync-policy <mode>", "--tail=<n>"
    return t.split(/\s*[\/,]\s*|\s+/).filter(w => /^--?[\w][\w-]*/.test(w)).map(w => w.match(/^--?[\w][\w-]*/)[0]);
  }
  // Subcommands: "serveraction", "storage get controllers -o", "app sync <app>"
  const m = t.match(/^([a-z][\w.-]*(?: [a-z][\w.-]*){0,2})(?=$|\s+[<\[-]|\s*\/)/);
  return m ? [m[1]] : [];
}
function addFlags(cmd, flags, file) {
  const tool = toolOf(cmd);
  if (!tool || !Array.isArray(flags)) return;
  const bucket = flagIndex[tool] || (flagIndex[tool] = {});
  for (const f of flags) {
    const tok = Array.isArray(f) ? f[0] : f && (f.flag || f.name);
    const desc = Array.isArray(f) ? f[1] : f && (f.desc || f.description);
    if (!tok || !desc) continue;
    // "kubectl explain" is filed under kubectl as "explain".
    for (const k of flagKeys(tok).map(k => k.startsWith(`${tool} `) ? k.slice(tool.length + 1) : k).filter(k => k && k !== tool)) if (!bucket[k]) bucket[k] = [String(desc).slice(0, 220), file];
  }
}

for (const jsFile of jsFiles) {
  const htmlFile = htmlFor(jsFile);
  const filePath = path.join(__dirname, jsFile);
  const content = fs.readFileSync(filePath, 'utf8');

  const match = content.match(/const\s+([A-Z0-9_]+_DATA)\s*=\s*(\[[\s\S]*?\n\]);/);
  if (!match) continue;

  let sections = [];
  try {
    sections = eval(match[2]);
  } catch (err) {
    console.error(`Error evaluating ${jsFile}:`, err.message);
    continue;
  }

  const sName = jsFile === 'app.js' ? 'linux' : jsFile.replace(/\.js$/, '');

  for (const s of sections) {
    if (!s || !Array.isArray(s.commands)) continue;
    for (const c of s.commands) {
      if (!c) continue;
      addFlags(c.cmd, c.flags, htmlFile);
      index.push({
        sName: sName,
        file: htmlFile,
        badge: s.badge || sName.toUpperCase(),
        id: c.id || '',
        sec: s.title || '',
        cmd: c.cmd || '',
        desc: c.desc || '',
        tip: c.tip || '',
        tags: Array.isArray(c.tags) ? c.tags.join(' ') : '',
        // Reference entries keep their text for search but have nothing to copy.
        ...((c.diagram || c.hideCode || isReference(c.cmd || '', jsFile)) ? { noCopy: true } : {})
      });
      if (Array.isArray(c.subcommands)) {
        for (const sub of c.subcommands) {
          if (Array.isArray(sub) && sub.length >= 2) {
            index.push({
              sName: sName,
              file: htmlFile,
              badge: s.badge || sName.toUpperCase(),
              id: c.id || '',
              sec: s.title || '',
              cmd: sub[0],
              desc: sub[1],
              tip: '',
              tags: Array.isArray(c.tags) ? c.tags.join(' ') : '',
              ...(isReference(String(sub[0]), jsFile) ? { noCopy: true } : {})
            });
          }
        }
      }
    }
  }
}

const outContent = `// Auto-generated Global Search Index across all ${jsFiles.length} cheat sheets
// Total indexed items: ${index.length}
window.GLOBAL_SEARCH_INDEX = ${JSON.stringify(index, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, 'global-search-index.js'), outContent, 'utf8');
const flagCount = Object.values(flagIndex).reduce((n, b) => n + Object.keys(b).length, 0);
fs.writeFileSync(path.join(__dirname, 'flag-index.js'), `// Auto-generated by build-index.js: flag and subcommand notes per tool, for "Explain a command".\nwindow.FLAG_INDEX = ${JSON.stringify(flagIndex)};\n`, 'utf8');
console.log(`flag-index.js: ${Object.keys(flagIndex).length} tools, ${flagCount} flags and subcommands.`);
console.log(`Successfully generated global-search-index.js across ${jsFiles.length} sheets with ${index.length} items.`);
